#!/usr/bin/env node
// ArchFlow diagram icon set generator.
//
// Draws every icon from isometric primitives (extruded shapes, cylinders,
// spheres, drawings mapped onto faces) so the whole set shares one style, one
// light direction and one scale. Each category has its own colour.
//
// Icons that replace the original isoflow pack keep its ids (server, cloud,
// desktop, ...), so existing diagrams pick up the new drawings automatically.
//
// Layout:
//   iso.mjs        projection, palette, primitives, SVG assembly
//   parts.mjs      drawings shared between icons (people, screens, glyphs)
//   sets/*.mjs     one file per category, one small function per icon
//
// Rendering contract with the app: every SVG has the same viewBox width
// (102, a 4x4 footprint is 100px wide) and its bottom edge is the bottom of
// the footprint, so all icons have the same scale on the canvas; only the
// height varies with how tall the object is.
//
// Usage: node scripts/icons/build-icons.mjs [--preview <file.json>]
// Writes packages/fossflow-app/src/icons/archflowIcons.ts

import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ICONS, render } from './iso.mjs';
import './sets/compute.mjs';
import './sets/network.mjs';
import './sets/communication.mjs';
import './sets/data.mjs';
import './sets/security.mjs';
import './sets/people.mjs';
import './sets/flow.mjs';
import './sets/business.mjs';
import './sets/shapes.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const OUT = resolve(ROOT, 'packages/fossflow-app/src/icons/archflowIcons.ts');

// Categories and their colours (every icon of a category uses its colour)
export const CATEGORIES = [
  { id: 'af-compute', pl: 'Serwery i komputery', en: 'Servers & computers', color: '#3b7be8' },
  { id: 'af-network', pl: 'Sieć', en: 'Network', color: '#7c5ce0' },
  { id: 'af-communication', pl: 'Komunikacja', en: 'Communication', color: '#12a5c8' },
  { id: 'af-data', pl: 'Dane', en: 'Data', color: '#1aa873' },
  { id: 'af-security', pl: 'Bezpieczeństwo', en: 'Security', color: '#e2543f' },
  { id: 'af-people', pl: 'Ludzie i organizacja', en: 'People & organisation', color: '#eba21c' },
  { id: 'af-flow', pl: 'Przepływ i procesy', en: 'Flow & process', color: '#d9508f' },
  { id: 'af-business', pl: 'Biznes i logistyka', en: 'Business & logistics', color: '#c9772e' },
  { id: 'af-shapes', pl: 'Kształty', en: 'Shapes', color: '#70809c' }
];

const only = process.env.ICONS_ONLY ? process.env.ICONS_ONLY.split(',') : null;
const built = [];
CATEGORIES.forEach((cat) => {
  ICONS.filter((def) => def.cat === cat.id && (!only || only.includes(def.id))).forEach((def) => {
    const { svg, warn } = render(def.draw, cat.color);
    warn.forEach((w) => console.warn(`! ${def.id}: ${w}`));
    built.push({
      id: def.id,
      category: def.cat,
      names: { pl: def.pl, en: def.en },
      svg,
      url: `data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`
    });
  });
});

const ids = new Set();
ICONS.forEach((def) => {
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(def.id)) throw new Error(`Bad icon id ${def.id}`);
  if (ids.has(def.id)) throw new Error(`Duplicate icon id ${def.id}`);
  if (!CATEGORIES.some((c) => c.id === def.cat)) throw new Error(`Unknown category ${def.cat}`);
  ids.add(def.id);
});

// Ids of the original isoflow pack; they must all be present
const LEGACY = 'block cache cardterminal cloud cronjob cube desktop diamond dns document firewall function-module image laptop loadbalancer lock mail mailmultiple mobiledevice office package-module paymentcard plane printer pyramid queue router server speech sphere storage switch-module tower truck-2 truck user vm'.split(' ');
const missing = LEGACY.filter((id) => !ids.has(id));
if (missing.length && !only && !process.argv.includes('--no-write')) throw new Error(`Missing legacy icon ids: ${missing.join(', ')}`);

const previewIdx = process.argv.indexOf('--preview');
if (previewIdx > 0) {
  const file = process.argv[previewIdx + 1];
  writeFileSync(file, JSON.stringify({ categories: CATEGORIES, icons: built.map(({ id, category, names, svg }) => ({ id, category, names, svg })) }));
  console.log(`Wrote preview data to ${file}`);
}
if (only || process.argv.includes('--no-write')) process.exit(0);

const ts = `// AUTO-GENERATED by scripts/icons/build-icons.mjs - do not edit by hand.
// ArchFlow diagram icon set: ${built.length} isometric icons in ${CATEGORIES.length} categories.

export interface ArchflowIconDef {
  id: string;
  collection: string;
  names: { pl: string; en: string };
  url: string;
}

export const ARCHFLOW_ICON_CATEGORIES = ${JSON.stringify(CATEGORIES.map(({ id, pl, en, color }) => ({ id, pl, en, color })), null, 2)};

export const ARCHFLOW_ICONS: ArchflowIconDef[] = [
${built.map((b) => `  { id: ${JSON.stringify(b.id)}, collection: ${JSON.stringify(b.category)}, names: ${JSON.stringify(b.names)}, url: ${JSON.stringify(b.url)} }`).join(',\n')}
];
`;
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, ts);
console.log(`Wrote ${built.length} icons to ${OUT}`);
